package gui

import (
	"os/exec"
	"runtime"
)

// The API supplies only a validated backup folder. No shell interprets the path, including
// in browser mode, where the browser itself cannot open a local Finder/Explorer window.
func showFolder(path string) error {
	var cmd *exec.Cmd
	switch runtime.GOOS {
	case "darwin":
		cmd = exec.Command("open", path)
	case "windows":
		cmd = exec.Command("explorer.exe", path)
	default:
		cmd = exec.Command("xdg-open", path)
	}
	if err := cmd.Start(); err != nil {
		return err
	}
	go func() { _ = cmd.Wait() }()
	return nil
}
